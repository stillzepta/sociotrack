"""
Pydantic data contracts for Person 1: AI Diagnostic Brain.
Defines RawPost, PostAuditPattern, and CreatorAuditReport.
"""

from typing import Dict, List, Optional
from pydantic import BaseModel, Field


class RawPost(BaseModel):
    """Raw social/Instagram post metadata and metrics."""
    post_id: str
    media_type: str = Field(..., description="Post media type: REELS, CAROUSEL_ALBUM, IMAGE")
    caption: str
    views_or_reach: int = Field(..., ge=0, description="Total views or reach")
    likes: int = Field(default=0, ge=0)
    comments: int = Field(default=0, ge=0)
    shares: int = Field(default=0, ge=0)
    saves: int = Field(default=0, ge=0)
    posted_hour_utc: int = Field(default=12, ge=0, le=23, description="Upload hour in UTC (0-23)")
    provenance: Dict[str, str] = Field(
        default_factory=lambda: {
            "likes": "Verified",
            "comments": "Verified",
            "shares": "Estimated",
            "saves": "Estimated",
            "views_or_reach": "Estimated",
        },
        description="Metric provenance: 'Verified' | 'Retrieved' | 'Estimated' | 'Demo data' | 'Not available'",
    )


class PostAuditPattern(BaseModel):
    """Identified content pattern with metric evidence and actionable recommendations."""
    pattern_title: str = Field(..., description="Short summary of the pattern, e.g., 'Contrarian Hook Reels'")
    metric_evidence: str = Field(..., description="Concrete stats, e.g., '2.8x higher shares-to-reach ratio'")
    why_it_happened: str = Field(..., description="Algorithm/audience psychological reason")
    actionable_recommendation: str = Field(..., description="Concrete direction for the creator's next upload")


class CreatorAuditReport(BaseModel):
    """Comprehensive diagnostic report: What's Working vs. What's Not."""
    creator_handle: str
    health_score: int = Field(..., ge=0, le=100, description="Scale 0-100 reflecting overall audience engagement quality")
    median_engagement_rate: float = Field(..., description="Overall median engagement rate percentage")
    top_performing_format: str = Field(..., description="Best performing media type (e.g., REELS, CAROUSEL_ALBUM)")
    whats_working: List[PostAuditPattern] = Field(default_factory=list, description="Patterns statistically outperforming baseline")
    whats_failing: List[PostAuditPattern] = Field(default_factory=list, description="Patterns dragging down reach or engagement")
    immediate_next_steps: List[str] = Field(default_factory=list, description="Top 3-5 immediate execution steps for creator")
    provenance_badge: str = Field(default="Retrieved", description="'Verified' | 'Retrieved' | 'Demo data'")
    data_source: str = Field(default="Live API", description="Data pipeline source description")
    crawled_at: Optional[str] = None


class PredictedContentConcept(BaseModel):
    """Specific high-probability content concept generated by the AI Brain."""
    concept_title: str = Field(..., description="Short title of the predicted winning concept")
    predicted_format: str = Field(..., description="REELS, CAROUSEL_ALBUM, or STATIC_IMAGE")
    hook_text: str = Field(..., description="Exact first 3 seconds hook or slide 1 title")
    structure_outline: str = Field(..., description="Hook -> Retention Body -> Call to Action breakdown")
    predicted_er: float = Field(..., description="Estimated Engagement Rate percentage")
    virality_rating: str = Field(default="High", description="Viral potential: Viral, High, Moderate")
    utility_rating: str = Field(default="Bookmark Magnet", description="Utility potential: Bookmark Magnet, High, Medium")
    suggested_call_to_action: str = Field(..., description="Specific CTA to trigger comments or shares")


class WinningFormatRanking(BaseModel):
    """Ranked content format recommendation with algorithmic justification."""
    format_name: str = Field(..., description="e.g. 'Contrarian 30s Reels'")
    win_probability_percent: int = Field(..., ge=0, le=100)
    why_it_works: str = Field(..., description="Algorithmic rationale for why this works for this audience")


class ContentPredictionReport(BaseModel):
    """Full response report from AI content prediction engine."""
    creator_handle: str
    data_source: str = Field(default="instagram_live_crawl", description="Source of ingested posts")
    posts_analyzed: int = Field(default=0)
    baseline_er: float = Field(default=0.0, description="Creator baseline engagement rate")
    top_performing_format: str = Field(default="REELS")
    winning_formats: List[WinningFormatRanking] = Field(default_factory=list)
    predicted_ideas: List[PredictedContentConcept] = Field(default_factory=list)
    content_to_kill: List[str] = Field(default_factory=list, description="Formats or angles that harm algorithmic distribution")
    recommended_weekly_cadence: str = Field(default="3x Reels, 2x Carousels")
    ai_confidence_score: int = Field(default=92, ge=0, le=100)


class DraftContentPredictionRequest(BaseModel):
    """Input payload to predict performance of a specific draft / hook / caption."""
    text: str = Field(..., description="Draft caption, hook, or script text")
    format: str = Field(default="REELS", description="REELS, CAROUSEL_ALBUM, or STATIC_IMAGE")
    platform: str = Field(default="instagram", description="instagram, linkedin, twitter, etc.")
    creator_handle: Optional[str] = Field(default=None)
    creator_baseline_er: Optional[float] = Field(default=None, description="Creator's historical baseline ER")
    niche: Optional[str] = Field(default=None)


class HookAnalysisScore(BaseModel):
    curiosity_score: int = Field(..., ge=0, le=100)
    clarity_score: int = Field(..., ge=0, le=100)
    urgency_score: int = Field(..., ge=0, le=100)
    cta_strength: int = Field(..., ge=0, le=100)
    reading_grade_level: str = Field(default="Grade 6-8 (Ideal for Social)")


class DraftContentPredictionResult(BaseModel):
    """Algorithmic pre-publish prediction for a piece of content."""
    predicted_er: float
    virality_score: int = Field(..., ge=0, le=100)
    utility_index: float
    engagement_tier: str  # "VIRAL", "HIGH", "ABOVE_AVERAGE", "AVERAGE", "UNDERPERFORMING"
    hook_analysis: HookAnalysisScore
    predicted_retention_percent: int
    strengths: List[str]
    weaknesses: List[str]
    suggested_rewrites: List[str]
    recommended_posting_hours: str
    recommended_audio_or_pacing: str
    provenance: str

